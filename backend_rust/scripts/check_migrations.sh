#!/usr/bin/env bash
# The migration is the schema. This checks a Postgres database against it, and it pins
# four things, because each one has a different way of going wrong silently:
#
#   1. every column's type and NOT NULL-ness (all 36 columns of the six tables, 28 of
#      them NOT NULL, not a sample — sqlx-postgres type-checks at run time, so a wrong
#      column type is a request failing in production rather than a compile error, and a
#      column made nullable is a `None` the Rust structs have no field for),
#   2. ids being GENERATED *ALWAYS* identity, so a supplied id is refused: the SQL form
#      of the bundle rule that ids are never trusted from the file,
#   3. every `ON CONFLICT` target the code uses — `split_sync.asset_id`,
#      `historical_prices (symbol, date)` and `uq_users_issuer_subj` — plus the
#      split-dedupe index, which is the #50 dedupe and is not a key at all,
#   4. that the database being inspected was built from *these* files: the ledger must
#      hold one successful row per `*.sql` on disk (at least one) and each row's stored
#      checksum must equal the sha384 of its file. A bare count match would still
#      certify a database migrated from an older copy of 0001_init.sql — 1 = 1 — which
#      is the staleness this check exists to catch.
#
# Shell rather than a Rust test because it has to run during the engine switch, before
# sqlx's postgres feature exists.
#
# Run it against a database that has the migrations applied:
#   nix-shell -p postgresql_18 --run 'bash scripts/dev-db.sh'
#   sqlx migrate run --no-dotenv --database-url "$DATABASE_URL" --source migrations
#   DATABASE_URL="$DATABASE_URL" bash scripts/check_migrations.sh
# Set MIGRATIONS_DIR if the files are not in ../migrations relative to this script.
set -euo pipefail
: "${DATABASE_URL:?run scripts/dev-db.sh and export DATABASE_URL}"
: "${MIGRATIONS_DIR:=$(dirname "${BASH_SOURCE[0]}")/../migrations}"

command -v psql >/dev/null \
  || { echo "FAIL psql is not installed — run inside: nix-shell -p postgresql_18 --run '...'"; exit 1; }
command -v sha384sum >/dev/null \
  || { echo "FAIL sha384sum is not installed (GNU coreutils); the ledger check cannot tie the database to the files"; exit 1; }

# -w so a password prompt cannot hang a non-tty job; ON_ERROR_STOP so a broken query is
# an error here rather than an empty string that looks like a missing column.
q() { psql -w "$DATABASE_URL" -v ON_ERROR_STOP=1 -tAc "$1"; }

want() { # table column type
  local t
  t=$(q "select data_type from information_schema.columns
          where table_schema='public' and table_name='$1' and column_name='$2'") \
    || { echo "FAIL could not read the type of $1.$2 from $DATABASE_URL"; exit 1; }
  [ -n "$t" ] || { echo "FAIL $1.$2 does not exist in $DATABASE_URL"; exit 1; }
  [ "$t" = "$3" ] || { echo "FAIL $1.$2 is '$t', expected '$3'"; exit 1; }
  echo "ok   $1.$2 = $3"
}

want_notnull() { # table column
  local n
  n=$(q "select is_nullable from information_schema.columns
          where table_schema='public' and table_name='$1' and column_name='$2'") \
    || { echo "FAIL could not read the nullability of $1.$2 from $DATABASE_URL"; exit 1; }
  [ "$n" = "NO" ] \
    || { echo "FAIL $1.$2 is nullable, but the migration declares it NOT NULL"; exit 1; }
  echo "ok   $1.$2 NOT NULL"
}

# Identity comes from pg_attribute.attidentity, not information_schema.columns.is_identity:
# `is_identity` is 'YES' for GENERATED *BY DEFAULT* too, and BY DEFAULT accepts a supplied
# id — the exact property this check exists to protect. 'a' is ALWAYS, 'd' is BY DEFAULT,
# empty is not an identity column at all.
want_identity() { # table column
  local a
  a=$(q "select attidentity from pg_attribute
          where attrelid = 'public.$1'::regclass and attname = '$2'") \
    || { echo "FAIL could not read the identity of $1.$2 from $DATABASE_URL"; exit 1; }
  case "$a" in
    a) echo "ok   $1.$2 identity = GENERATED ALWAYS" ;;
    d) echo "FAIL $1.$2 is GENERATED BY DEFAULT AS IDENTITY: a supplied id would be accepted, which is the bundle rule this check exists for"; exit 1 ;;
    *) echo "FAIL $1.$2 is not an identity column (attidentity='$a'), expected GENERATED ALWAYS (a)"; exit 1 ;;
  esac
}

want_pk() { # table expected-primary-key
  local d
  d=$(q "select coalesce(pg_get_constraintdef(oid), '') from pg_constraint
          where conrelid = 'public.$1'::regclass and contype = 'p'") \
    || { echo "FAIL could not read the primary key of $1 from $DATABASE_URL"; exit 1; }
  [ "$d" = "$2" ] || { echo "FAIL $1 primary key is '$d', expected '$2'"; exit 1; }
  echo "ok   $1 primary key = $2"
}

# A named unique index, keyed on exactly the given columns. Every ON CONFLICT target in
# the code needs one: with no matching index the statement is rejected when the plan is
# built, so the request that first reaches that line fails.
want_unique() { # table index-name "(col, ...)"
  local row uniq cols
  row=$(q "select concat_ws('|', i.indisunique,
                 (select string_agg(a.attname, ', ' order by k.ord)
                    from unnest(i.indkey) with ordinality as k(attnum, ord)
                    join pg_attribute a on a.attrelid = i.indrelid and a.attnum = k.attnum))
            from pg_class t
            join pg_namespace n on n.oid = t.relnamespace
            join pg_index i on i.indrelid = t.oid
            join pg_class x on x.oid = i.indexrelid
            where n.nspname = 'public' and t.relname = '$1' and x.relname = '$2'") \
    || { echo "FAIL could not read index $2 from $DATABASE_URL"; exit 1; }
  [ -n "$row" ] \
    || { echo "FAIL $1.$2 does not exist, and an ON CONFLICT target needs a matching unique index"; exit 1; }
  IFS='|' read -r uniq cols <<<"$row"
  [ "$uniq" = "t" ] || { echo "FAIL $1.$2 must be UNIQUE, it is not"; exit 1; }
  [ "($cols)" = "$3" ] || { echo "FAIL $1.$2 keys on ($cols), expected $3"; exit 1; }
  echo "ok   $1.$2 = unique, keyed on $3"
}

# The gate inspects a database; this is what ties that database to these exact files.
# sqlx stores sha384(file contents) as the checksum (sqlx-core-0.8.6
# src/migrate/migration.rs:25), so a database migrated from an older copy of a file
# fails on content rather than passing a bare count comparison.
want_migration_ledger() {
  local dir="$MIGRATIONS_DIR" files n applied f base v d sum stored
  [ -d "$dir" ] \
    || { echo "FAIL migrations directory '$dir' not found; set MIGRATIONS_DIR"; exit 1; }
  files=$(find "$dir" -maxdepth 1 -type f -name '*.sql' | LC_ALL=C sort)
  n=$(printf '%s\n' "$files" | sed '/^$/d' | wc -l | tr -d '[:space:]')
  [ "$n" -gt 0 ] \
    || { echo "FAIL no *.sql file found in '$dir': there is nothing to tie $DATABASE_URL to"; exit 1; }
  applied=$(q "select count(*) from _sqlx_migrations where success") \
    || { echo "FAIL cannot read _sqlx_migrations from $DATABASE_URL — has 'sqlx migrate run' been applied to it?"; exit 1; }
  [ "$applied" = "$n" ] \
    || { echo "FAIL $DATABASE_URL holds $applied applied migration(s) but $dir holds $n .sql file(s): this database is not at the schema the gate is checking"; exit 1; }
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    base=$(basename "$f")
    v=${base%%_*}
    case "$v" in
      ''|*[!0-9]*) echo "FAIL '$base' is not named <version>_<description>.sql"; exit 1 ;;
    esac
    v=$((10#$v))
    d=${base#*_}
    d=${d%.sql}
    sum=$(sha384sum "$f" | cut -d' ' -f1)
    stored=$(q "select encode(checksum, 'hex') from _sqlx_migrations
                  where version = $v and description = '$d' and success") \
      || { echo "FAIL cannot read the stored checksum of $base from $DATABASE_URL"; exit 1; }
    [ -n "$stored" ] \
      || { echo "FAIL $base is on disk but not applied in $DATABASE_URL (version $v, description '$d')"; exit 1; }
    [ "$stored" = "$sum" ] \
      || { echo "FAIL $base on disk is sha384 $sum but $DATABASE_URL applied it as $stored: this database was migrated from a different copy of this file"; exit 1; }
  done <<<"$files"
  echo "ok   _sqlx_migrations = $applied applied, each stored checksum matching its file in $dir"
}

# The split dedupe is an index, not a query. `apply_split_events` inserts with
# `ON CONFLICT DO NOTHING` and has no read-based check of its own, so a schema that
# drops `uq_split_asset_date` silently reintroduces #50 — two concurrent syncs doubling
# a split adjustment and corrupting cost basis. A gate that checked only tables and
# column types would have passed that schema, which makes it complicit in the bug it
# exists to prevent, so the index itself is asserted: present, unique, partial on SPLIT,
# and keyed on the UTC calendar day.
want_split_dedupe_index() {
  local row uniq partial pred def
  row=$(q "select concat_ws('|', i.indisunique, (i.indpred is not null),
                             coalesce(pg_get_expr(i.indpred, i.indrelid), ''),
                             pg_get_indexdef(i.indexrelid))
            from pg_class t
            join pg_namespace n on n.oid = t.relnamespace
            join pg_index i on i.indrelid = t.oid
            join pg_class x on x.oid = i.indexrelid
            where n.nspname = 'public' and t.relname = 'transactions'
              and x.relname = 'uq_split_asset_date'") \
    || { echo "FAIL could not read uq_split_asset_date from $DATABASE_URL"; exit 1; }
  [ -n "$row" ] \
    || { echo "FAIL transactions.uq_split_asset_date is missing; apply_split_events dedupes by conflict and has no read-based check (#50)"; exit 1; }
  IFS='|' read -r uniq partial pred def <<<"$row"
  [ "$uniq" = "t" ] || { echo "FAIL uq_split_asset_date must be UNIQUE, it is not"; exit 1; }
  [ "$partial" = "t" ] \
    || { echo "FAIL uq_split_asset_date must be partial (WHERE type = 'SPLIT'); a full index would constrain every transaction type"; exit 1; }
  case "$pred" in
    *"type = 'SPLIT'"*) ;;
    *) echo "FAIL uq_split_asset_date predicate is '$pred', expected type = 'SPLIT'"; exit 1 ;;
  esac
  case "$def" in
    *"AT TIME ZONE 'UTC'"*::date*) ;;
    *) echo "FAIL uq_split_asset_date must key on the UTC calendar day, (date AT TIME ZONE 'UTC')::date; definition is: $def"; exit 1 ;;
  esac
  case "$def" in
    *"(asset_id,"*) ;;
    *) echo "FAIL uq_split_asset_date must lead with asset_id; definition is: $def"; exit 1 ;;
  esac
  echo "ok   transactions.uq_split_asset_date = unique, partial on SPLIT, keyed on (asset_id, UTC day)"
}

# --- users --------------------------------------------------------------------------
# token_version is BIGINT because auth/guard.rs decodes it into an i64 and sqlx-postgres
# will not decode INT4 into i64; INTEGER would fail every authenticated request.
want users id            bigint
want users issuer        text
want users subj          text
want users email         text
want users name          text
want users is_active     boolean
want users token_version bigint
want users created_at    "timestamp with time zone"
want users last_login_at "timestamp with time zone"
want_notnull users id
want_notnull users issuer
want_notnull users subj
want_notnull users is_active
want_notnull users token_version
want_notnull users created_at

# --- portfolios ---------------------------------------------------------------------
want portfolios id            bigint
want portfolios owner_id      bigint
want portfolios name          text
want portfolios description   text
want portfolios currency      text
want portfolios base_currency text
want_notnull portfolios id
want_notnull portfolios name
want_notnull portfolios currency
want_notnull portfolios base_currency

# --- assets -------------------------------------------------------------------------
want assets id           bigint
want assets portfolio_id bigint
want assets symbol       text
want assets name         text
want assets asset_type   text
want assets sector       text
want assets currency     text
want assets isin         text
want_notnull assets id
want_notnull assets portfolio_id
want_notnull assets symbol
want_notnull assets name
want_notnull assets asset_type
want_notnull assets currency

# --- transactions -------------------------------------------------------------------
# price/quantity/fee stay TEXT by policy (decimal as a string, spec §3); date is
# timestamptz, which is also what uq_split_asset_date's UTC-day expression needs.
want transactions id       bigint
want transactions asset_id bigint
want transactions type     text
want transactions quantity text
want transactions price    text
want transactions fee      text
want transactions date     "timestamp with time zone"
want_notnull transactions id
want_notnull transactions asset_id
want_notnull transactions type
want_notnull transactions quantity
want_notnull transactions price
want_notnull transactions fee
want_notnull transactions date

# --- historical_prices --------------------------------------------------------------
want historical_prices symbol      text
want historical_prices date        date
want historical_prices close_price text
want_notnull historical_prices symbol
want_notnull historical_prices date
want_notnull historical_prices close_price

# --- split_sync ---------------------------------------------------------------------
# last_synced_at is DATE, not TIMESTAMPTZ: it is written as date_naive() and compared as
# a calendar day, so storing it as an instant would let a session timezone move the
# 30-day throttle window (#38).
want split_sync asset_id       bigint
want split_sync last_synced_at date
want split_sync covered_from   date
want_notnull split_sync asset_id
want_notnull split_sync last_synced_at

# --- keys, identity, and the ledger -------------------------------------------------
want_identity users        id
want_identity portfolios   id
want_identity assets       id
want_identity transactions id

# The two keys a query is written against rather than inferred: `split_sync` is upserted
# and deleted by asset_id alone, and price restore upserts on (symbol, date).
want_pk split_sync        "PRIMARY KEY (asset_id)"
want_pk historical_prices "PRIMARY KEY (symbol, date)"

# The third ON CONFLICT target: provision_or_update inserts the user row with
# `ON CONFLICT (issuer, subj) DO NOTHING` (auth/oidc.rs:304), so without this index every
# first login fails when the plan is built rather than writing a duplicate identity.
want_unique users uq_users_issuer_subj "(issuer, subj)"

want_split_dedupe_index
want_migration_ledger

echo "schema shape ok"
